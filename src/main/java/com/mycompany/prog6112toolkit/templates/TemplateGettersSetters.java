package com.mycompany.prog6112toolkit.templates;

public class TemplateGettersSetters {

    // Private variables protect the object's data.
    private String name;
    private int value;

    // Getter returns the name.
    public String getName() {
        return name;
    }

    // Setter changes the name.
    public void setName(String name) {
        this.name = name;
    }

    // Getter returns the value.
    public int getValue() {
        return value;
    }

    // Setter changes the value.
    public void setValue(int value) {
        this.value = value;
    }
}
