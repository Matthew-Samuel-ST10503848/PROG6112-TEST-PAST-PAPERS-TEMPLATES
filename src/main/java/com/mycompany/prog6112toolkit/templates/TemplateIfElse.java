package com.mycompany.prog6112toolkit.templates;

public class TemplateIfElse {

    public static void main(String[] args) {

        // Store a value that we want to test.
        int total = 75;

        // Check whether the value meets the condition.
        if (total >= 50) {

            // This runs when the condition is true.
            System.out.println("Pass");

        } else {

            // This runs when the condition is false.
            System.out.println("Fail");
        }
    }
}
